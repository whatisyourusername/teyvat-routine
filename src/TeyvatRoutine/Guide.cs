• 전투 도중 자동 찾기는 전투 전용 문구를 ‘전투 중 화면 등록’으로 등록하세요. 현재 비경의 ‘처치한 마물:’처럼 고정 문구를 쓰고 변하는 숫자와 평소 HUD는 제외하세요.
• 전투 완료면 보상으로, 보상 화면이면 재도전 또는 마지막 보상 뒤 다음 작업으로 이어집니다. 임의의 메뉴·이동 녹화 한가운데 입력 위치를 복원하는 기능은 아닙니다. 해당 동작의 등록된 시작 화면으로 맞추거나 다음 동작을 직접 고르세요.

04 전투 — 클리어까지 반복
• 04 비경 반복 → 전투 → 전투 사이클 설정에서 켜고, ‘녹화 분석 · 추천값 채우기’ → ‘전투 설정 적용’을 누릅니다.
• 원본 녹화는 그대로 보관합니다. 첫 시도에 도전 시작을 재생하고, 추가 시도에는 지정한 전투 부분만 반복합니다. 녹화를 새로 하면 이전 반복 경계는 해제됩니다.
• 현재 파티의 원본은 2→4→3→1 순서입니다. 시험 순서는 2 E 두 번 → 3 E → 클릭 낙하공격 → 짧은 대기 → 4 E → 1번 기존 딜링입니다. 시험 순서의 3번 E는 기본 100ms, 낙공 입력 후 대기는 400ms입니다. 원본 녹화 순서로 언제든 돌아갈 수 있습니다.
• ‘최소 시작 간격’은 같은 사이클의 시작 사이 최소 대기입니다. 카메라 정렬·화면 인식에 걸리는 시간만큼 실제 간격이 늘어날 수 있습니다. 현재 녹화의 추천 간격은 27초입니다. 쿨타임이 긴 파티는 직접 늘리세요.
• 선택하면 추가 사이클 직전에 일반 공격 → 가운데 휠 클릭으로 시점을 맞춥니다. 게임의 자동 방향 전환을 이용하는 동작이며 멀리 있는 적을 찾아 이동하지는 않습니다.
• 반복 중 완료 이미지는 반드시 계속 확인하며, 연속 2번 확인하면 누른 입력을 놓고 보상 단계로 넘어갑니다. 횟수 또는 시간 제한까지 클리어를 확인하지 못하면 전체 루틴을 중단합니다. 기본 최대 6사이클, 한 전투 180초입니다. 왼쪽의 비경 보상 횟수와 별개입니다.
• 완료 이미지는 클리어 후의 ‘자동으로 나갑니다’처럼 고정 문구를 사용하고 변하는 초 숫자를 제외하세요. ‘금색 글자만 비교’는 금색 문구의 배경 변화를 줄입니다. 흰색이나 다른 색의 완료 이미지에는 해제하세요.
• 시험 순서의 2번 E 간격은 첫 E를 놓은 뒤 기본 500ms입니다. ‘2번 E 재입력 아이콘 → 쿨타임 표시로 발동 확인’을 켜면 첫 E 뒤 바뀐 아이콘을 연속 2회 확인하고 즉시 두 번째 E를 보냅니다.
• 이후 소수점 쿨타임 숫자가 연속 2회 보이면 두 번째 E 발동으로 판단합니다. 아이콘이 계속 재입력 상태일 때만 최대 3회 재시도합니다. 재입력 아이콘 2초 / 쿨타임 확인 3초 안에 확인하지 못하면 중단합니다.
• 두 번째 E 발동 확인 뒤 최소 500ms 모션 대기를 둡니다. 파티창 대기를 켜면 오른쪽 3번 이름이 두 화면 연속 밝아진 뒤 교체하며, 2초 안에 확인하지 못하면 중단합니다. 이는 교체 가능 표시를 확인하는 기능이며 교체 성공 자체를 확인하지는 않습니다. 3번 키를 놓은 뒤 E까지도 최소 250ms를 둡니다.
• 3번 파티 이름은 2번을 조작하며 모션이 끝난 상태에서 등록합니다. 밝은 이름만 선택하고 숫자 3·초상화·HP는 제외하세요. 파티·해상도를 바꾸면 다시 등록하거나 파티창 대기를 끄세요. 스킬 인식 테스트에서 함께 확인할 수 있습니다. 낙공 후 대기는 착지 감지가 아닌 마우스 입력을 놓은 시점부터 계산합니다.
• 등록된 현재 2번 캐릭터용 기능입니다. 다른 파티나 해상도에서는 이미지를 다시 등록하거나 끄세요. 재입력 아이콘은 E 글자를 제외하고 선택합니다. 쿨타임 영역은 13.5처럼 두 자리 초가 들어가도록 등록합니다. ‘스킬 인식 테스트’는 입력 없이 현재 점수를 보여줍니다.
• 쿨타임 숫자의 표시 여부를 판별하며 13.5라는 값 자체를 읽지는 않습니다. 그 외 E·Q, 원소 에너지와 파티 자동 학습은 인식하지 않습니다. Q가 발동하지 않아도 녹화된 다음 공격을 계속합니다.
• 보상 수령 녹화와 레진 선택 흐름은 변경하지 않습니다.

