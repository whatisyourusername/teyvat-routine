• 실행 시 이미 완료 화면이면 입력을 보내지 않고 구간을 완료할 수 있습니다. 다른 단계에도 공통으로 보이는 HUD는 완료 이미지로 쓰지 마세요.
• 이 옵션은 자동 재생에 적용됩니다. 녹화 종료는 Alt+Tab → 저장 버튼으로 합니다.

04 비경 반복의 보상 나무를 찾아 접근하기 — 처음 한 번 등록
1. 왼쪽 ‘04 비경 반복’ → 오른쪽 ‘보상 수령’을 선택하고 ‘화면에서 보상 나무를 찾아 접근’을 켭니다.
2. 전투 종료 후 나무가 화면 중앙 부근에 보일 때 ‘나무 모습 추가’를 누릅니다. 특징적인 줄기·가지를 선택하고 주변 배경은 적게 포함합니다.
   먼 거리/중간 거리/가까운 거리의 모습을 1~5개 등록할 수 있습니다. 작은 미니맵 아이콘이 아니라 게임 화면의 실제 나무 모양을 선택합니다.
3. ‘인식만 테스트’로 나무 위치에 초록 사각형이 표시되는지 확인합니다. 이 버튼은 이동이나 상호작용을 하지 않습니다.
   ‘나무 접근만 테스트’는 실제로 회전·이동하고 F 표시를 두 번 확인하면 자동 정지합니다. 보상 녹화는 재생하지 않습니다.
   캐릭터나 동행물이 나무를 가리면 잠시 기다린 뒤 마지막으로 확인한 방향을 작게 보정합니다. 재검출 전에는 전진하지 않습니다.
   이미 정상 전진을 4번 이상 한 뒤 안정적인 나무 방향이 확인되면, 높이 보정 4회 사이에 최대 200ms씩 짧게 전진합니다. 한 번의 접근에서 최대 3번이며 F 표시·완료 화면·중단 요청을 우선합니다.
   ‘시작 시 축소량’은 기본 3칸입니다. 휠을 아래로 굴려 캐릭터와 카메라 사이 거리를 늘립니다. 0~6칸을 설정할 수 있고 0은 축소하지 않습니다.
   이후 ‘접근 시작 시 휠 버튼 클릭으로 정면 보기’가 켜져 있으면 가운데 버튼을 한 번 클릭합니다. 각 동작 후 0.6초 뒤 화면을 새로 확인합니다.
   축소와 정면 보기는 시작할 때만 합니다. 이미 F 도착 표시가 보이거나 구간이 완료되었으면 두 동작 모두 생략합니다.
   게임의 가운데 버튼 기능을 바꾼 경우 이 옵션을 끄세요. 휠을 굴리는 스크롤 입력과는 다릅니다.
   ‘접근 설정’의 ‘시점 높이 자동 조절’은 기본으로 켜져 있습니다. 나무가 없으면 위아래 높이를 바꿔 탐색하고,
   검출한 나무 부분이 화면 세로 23~53%를 벗어나면 높이를 보정합니다. 보정을 시작하면 30~46%까지 맞춘 뒤 전진합니다.
   ‘나무가 크게 보이거나 보정이 반복되면 상하 속도 높이기’가 기본으로 켜져 있습니다. 등록 이미지의 검출 크기와 연속 보정 횟수에 따라 입력량을 늘립니다.
   한 번의 상하 입력은 일반 검출에서 최대 60px, 가로/세로 검출 크기가 화면의 22% 이상일 때 최대 96px입니다. 실제 거리를 읽는 기능은 아닙니다.
   연속 16회 보정 동안 높이가 개선되지 않으면 멈춥니다. 개선되거나 정상 높이로 돌아오면 실패 횟수를 초기화합니다. F 도착 확인이 항상 우선입니다.
   게임의 상하 조작을 반전했다면 ‘상하 반전’을 켜세요. 상하 보정량/탐색량은 카메라 감도에 맞게 조절할 수 있습니다.
   절대 카메라 각도나 지형 좌표를 읽는 기능은 아닙니다. 등록한 모습이 완전히 가려졌거나 다른 장면이면 제한 시간 후 멈춥니다.
4. 직접 나무에 접근해 상호작용 표시가 보이면 ‘도착 F 표시 등록’을 누릅니다. F 키와 해당 상호작용 이름을 함께 선택하세요.
5. 그 위치에서 ‘보상 조작 녹화’를 누르고 F → 농축레진 사용 → 보상 화면까지 녹화합니다. 걸어가는 동작은 이 녹화에 포함하지 않습니다.
   녹화 시작 시 F 일치도가 낮아도 수동 녹화를 시작하며, 점수와 진단 화면을 로그에 남깁니다. 자동 접근에서는 F 표시를 연속 2회 확인해야 멈춥니다.
6. Alt+Tab → ‘녹화 종료 · 저장’. ‘완료 화면’에는 아이템 보상 화면의 고유 표시를 등록합니다.
7. 전투가 끝난 위치로 돌아가 ‘선택 구간 테스트’로 확인합니다. 실제 보상 조작 녹화를 재생하므로 레진을 소비할 수 있습니다.

화면 인식 조정과 진단
• ‘화면 인식 테스트’는 현재 화면의 시작/완료/도착 점수와 통과 기준을 표시합니다. 게임 입력은 보내지 않습니다.
• ‘화면 인식 기준 설정’에서 각각 0.65~0.99, 위치 오차 0~100px를 조절할 수 있습니다. 기본 기준은 0.86, 위치 오차는 18px입니다.
• 밝기 변화에 덜 민감한 형태 상관도와 색상 유사도를 함께 비교합니다. 점수는 인식 정확도의 확률이 아닙니다.
• 이전 프로필의 기본 0.91/8px는 0.86/18px로 변환하며 직접 바꾼 값은 유지합니다. 전체 화면보다 해당 단계에서만 나타나는 고유 글자/아이콘을 등록하세요.
• 테스트 화면과 점수는 data/diagnostics에 PNG/TXT로 저장됩니다. 나무 테스트는 초록색=통과, 주황색=최상위 후보이지만 기준 미달입니다.

나무 접근 방식과 조정
• 화면 가장자리까지 포함해 등록 이미지와 비슷한 모습을 여러 크기로 찾습니다. 일반적인 사물 분류 AI나 장애물 회피 기능은 없습니다.
• 나무 기본 기준은 0.78입니다. 이전 기본 0.84는 업데이트 시 변환합니다. 1위/2위 후보 점수와 미검출 이유를 테스트 화면에서 확인할 수 있습니다.
• 같은 대상을 연속 확인한 뒤 방향이 벗어나 있으면 시점을 돌리고, 중앙에 있으면 기본 120ms씩 W로 전진하며 다시 확인합니다.
• ‘방향이 안정되면 빠르게 접근’을 켜면 높은 일치도와 정면 방향을 확인했을 때 기본 600ms씩 전진합니다. 나무가 크게 보이거나 높이·방향이 벗어나면 기본 짧은 전진으로 돌아갑니다. 빠른 전진은 200~800ms로 조정할 수 있습니다.
• 빠른 접근 중 F 표시는 약 80ms 간격으로 확인하며 캡처·인식 시간이 더해집니다. 첫 감지에 이동을 멈추고 다음 화면에서도 확인해야 도착으로 처리합니다. 매 전진 후 새 나무 화면을 확인하며, 대상이 사라지거나 크기가 갑자기 변하면 연속 확인부터 다시 시작합니다.
• 나무가 사라지거나 후보가 비슷하면 전진하지 않고 제자리에서 탐색합니다. 도착 F 표시를 연속 2회 확인해야 보상 조작을 시작합니다.
• 기본 60초 또는 탐색 회전 48회 제한을 넘기면 구간을 중단합니다. 실패한 구간을 보상 완료로 세지 않습니다.
• 접근 설정에서 전진 시간, 시점 보정량, 탐색 회전량, 제한 시간과 좌우 반전을 조정할 수 있습니다. 너무 많이 돌아가면 시점 보정량을 줄이세요.
• 나무가 위·아래로 잘려 보이거나 배경/조명/각도가 크게 다르면 추가 이미지를 등록하고 시작 카메라 높이를 맞추세요. 미검출 시 인식 기준을 무작정 낮추지 마세요.
• 새 접근 모드는 기존 이동 녹화를 따로 보관합니다. 체크를 끄면 이전 구간 녹화를 다시 사용할 수 있습니다.
• 나무 접근 모드에서는 시작 화면 대신 나무 탐색과 도착 F 표시를 사용합니다. 도착 후 조작 녹화는 별도 저장됩니다.

마우스 기록과 시점 기준
• ‘녹화 시 커서 표시로 메뉴/카메라 자동 전환’이 기본으로 켜집니다. Windows 커서가 보이면 메뉴 좌표, 숨겨지면 Raw 상대 이동을 기록합니다.
• 게임이 커서를 별도로 그리는 환경에서는 자동 판정이 다를 수 있습니다. 옵션을 끄고 수동 모드를 쓰거나 녹화 중 Ctrl+Alt+Home을 누르세요. 해당 녹화는 수동 모드로 전환됩니다.
• 카메라 모드에서는 숨겨진 커서의 화면 밖 위치만으로 녹화를 멈추지 않습니다. 실제로 다른 창에 포커스가 이동하면 기존처럼 멈춥니다.
• 저장 로그에 Raw 수신 수, 절대형 Raw 수, 오류 수, 메뉴 영역 밖 이벤트, 모드 변경 수가 기록됩니다. 절대형 Raw 장치의 카메라 이동은 현재 지원하지 않습니다.
• 기존 녹화에서 빠졌거나 잘못된 모드로 저장된 움직임은 복원할 수 없습니다. 그 구간만 다시 녹화하세요. 게임의 카메라 감도·DPI 설정은 녹화와 재생 때 같게 유지하세요.
• 전투 시작 위치에서 원하는 방향을 바라본 뒤 ‘시점 기준 등록’으로 고정 문양/기둥 등을 선택하고 ‘재생 전에 시점 기준물 정렬’을 켭니다.
• 재생 전에 기준물을 찾아 등록 당시 화면 위치에 맞춥니다. 앞으로 걷지 않으며 20초/32회 탐색 한도 안에서 정렬하지 못하면 중단합니다. 나무 접근 모드에는 적용하지 않습니다.
• 이 기능은 상대적인 화면 정렬입니다. 월드 좌표/절대 방위/실시간 적 위치를 읽지 않으며, 전투 중간에 계속 방향을 추적하지 않습니다. 시작 위치가 크게 다르거나 기준물이 가려져 있으면 실패할 수 있습니다.

등록 순서와 초기화
• 시작·완료 화면을 먼저 등록해도 구간 녹화를 할 수 있습니다. 게임을 해당 구간의 시작 상태로 돌린 뒤 녹화하세요.
• 입력을 다시 녹화해도 이미 등록한 시작·완료 화면은 유지됩니다. 변경하려면 해당 화면 등록 버튼을 누르세요.
• ‘구간 초기화’는 선택 구간의 입력 녹화, 시작·완료 화면, 나무 이미지, 도착 표시, 도착 후 조작 녹화, 시점 기준 이미지를 지웁니다. 다른 구간/해상도와 모드·시간 설정은 유지됩니다.
• 초기화 직전 프로필은 data/backups/before-reset-…json에 보관합니다. ‘불러오기’로 복원할 수 있습니다.

단축키
Ctrl+Alt+Home: 녹화 도중 메뉴 좌표 ↔ 카메라 이동 전환
Ctrl+Alt+End: 실행 즉시 중단 / 현재 녹화 취소
녹화 시작: ‘구간 녹화’ 버튼. F1~F12와 Esc는 게임 입력으로 녹화하며, F6/F8/F9도 프로그램 단축키로 사용하지 않습니다.
F13~F24, 숫자패드 연산자, Insert/Delete/Home/End/PageUp/PageDown, 기호 키 등도 기록합니다.
프로그램 조합키 두 개와 창 전환용 Alt+Tab/Alt+Esc/Windows 키는 녹화에서 제외합니다. 단독 Tab/Esc/End/Home은 정상 기록합니다.
기본 종료 방법은 Alt+Tab → ‘녹화 종료 · 저장’입니다. ‘녹화 취소’는 이번 녹화를 버립니다.
녹화 중 다른 창으로 전환하면 입력 수집을 멈추고 저장을 기다립니다. 게임으로 돌아가도 자동 재개되지 않습니다.
Alt+Tab의 Tab 입력, 저장 버튼 클릭, 저장을 기다리는 시간은 녹화에 포함되지 않습니다.
자동 재생 중에는 창 전환 시 재생을 중단하고 누른 입력을 해제합니다.
Ctrl+Alt+End 등록 실패 시 실제 자동 재생만 잠깁니다. 수동 녹화/저장은 가능합니다.
단축키 진단: 로그에 Ctrl+Alt+Home / Ctrl+Alt+End 등록 결과와 오류 번호를 남깁니다. ‘입력 목록’에서 F1, Escape 등의 키 이름을 확인할 수 있습니다.
이전 버전에서 빠진 키 입력은 복구할 수 없으므로 해당 구간을 다시 녹화해야 합니다. 기존 시작·완료 이미지는 유지됩니다.

창 모드와 해상도 설정
• 게임 설정에서 원하는 해상도·창 모드를 먼저 적용합니다.
• ‘현재 창 크기’ 버튼이 실제 게임 렌더링 영역의 크기를 읽고 해당 프로필을 불러옵니다.
• UHD 3840×2160 / QHD 2560×1440 / FHD 1920×1080을 선택하거나 직접 WxH를 입력하고 적용할 수 있습니다.
• 이 설정은 프로그램의 프로필 선택입니다. 게임이나 Windows의 해상도를 직접 변경하지 않습니다.
• 해상도별 녹화와 이미지가 data/profiles/가로x세로.json에 각각 저장됩니다. 새 해상도는 별도 등록이 필요합니다.
• 메뉴 좌표는 게임 창 내부 비율로 저장하므로 같은 크기의 창을 다른 위치로 옮겨도 됩니다.
• Windows 150% 등의 배율과 게임의 실제 픽셀 크기를 구분합니다. 캡처 미리보기만 화면에 맞게 축소됩니다.

